const DICTS: Record<string, Dict> = { en, fr, es, de, sw, zh, pt, ar, hi, ig, ha, yo };

export function isSupportedLang(code: string | null | undefined): code is LangCode {
  return !!code && Object.prototype.hasOwnProperty.call(DICTS, code);
}

export function translator(lang: string | null | undefined) {
  const dict = (isSupportedLang(lang) ? DICTS[lang] : en) ?? en;
  return (key: string) => dict[key] ?? en[key] ?? key;
}

export function languageName(code: string): string {
  return LANGUAGES.find((l) => l.code === code)?.label ?? "English";
}

export function isRtl(code: string | null | undefined): boolean {
  return !!code && RTL_LANGS.includes(code as LangCode);
}

/** Best default from the browser, falling back to English. */
export function detectBrowserLang(): LangCode {
  if (typeof navigator === "undefined") return "en";
  const raw = (navigator.language || "en").slice(0, 2).toLowerCase();
  return isSupportedLang(raw) ? raw : "en";
}
